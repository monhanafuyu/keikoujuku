A. 意思の力で我慢するのは不可能です。「物理的に距離を置く」仕組みを作ってください。勉強中はスマホを別の部屋の親に預ける、スクリーンタイムアプリで特定のアプリをロックするなど、強制力を持たせることが効果的です。

**Q. 計画が遅れすぎて、見るのも嫌になってきました。**
A. 一度その計画はリセットしましょう。過去の遅れを取り戻そうとすると無理な計画になります。今日を起点として、「今から試験日までに何ができるか」を現実的なペースで再構築し直すことが重要です。

